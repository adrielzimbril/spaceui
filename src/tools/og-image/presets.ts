/**
 * Proportionally scales typographic sizes, paddings, and radii when switching card dimensions
 * so that card designs maintain visual balance without shrinking or overflowing.
 */
export function applySizeScale(prev: OgState, newW: number, newH: number): OgState {
  if (prev.width === newW && prev.height === newH) return prev
  const oldArea = prev.width * prev.height
  const newArea = newW * newH
  if (oldArea <= 0 || newArea <= 0) {
    return { ...prev, width: newW, height: newH }
  }
  const ratio = Math.sqrt(newArea / oldArea)
  const scale = (val: number, min: number, max: number) => Math.min(max, Math.max(min, Math.round(val * ratio)))

  const scaleChip = (c: Chip): Chip => ({
    ...c,
    padX: scale(c.padX, 6, 80),
    padY: scale(c.padY, 4, 60),
    radius: scale(c.radius, 0, 999),
  })

  return {
    ...prev,
    width: newW,
    height: newH,
    titleSize: scale(prev.titleSize, 24, 200),
    subtitleSize: scale(prev.subtitleSize, 14, 80),
    brandSize: scale(prev.brandSize, 14, 60),
    tagsSize: scale(prev.tagsSize, 10, 50),
    footerSize: scale(prev.footerSize, 10, 50),
    badgeSize: scale(prev.badgeSize, 12, 50),
    logoSize: scale(prev.logoSize, 20, 160),
    padding: scale(prev.padding, 16, 200),
    radius: scale(prev.radius, 0, 100),
    showcaseSize: scale(prev.showcaseSize, 24, 120),
    showcaseGap: scale(prev.showcaseGap, 6, 40),
    chips: {
      badge: scaleChip(prev.chips.badge),
      brand: scaleChip(prev.chips.brand),
      title: scaleChip(prev.chips.title),
      subtitle: scaleChip(prev.chips.subtitle),
      tags: scaleChip(prev.chips.tags),
      footer: scaleChip(prev.chips.footer),
    },
  }
}

export function cloneChips(c: Record<ChipKey, Chip>): Record<ChipKey, Chip> {
  return Object.fromEntries(Object.entries(c).map(([k, v]) => [k, { ...v }])) as Record<ChipKey, Chip>
}

