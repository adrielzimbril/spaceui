export function presetState(p: Preset, prev: OgState): OgState {
  const base = { ...DEFAULT_OG_STATE, chips: cloneChips(DEFAULT_OG_STATE.chips) } as OgState
  KEEP.forEach((k) => ((base as unknown as Record<string, unknown>)[k as string] = prev[k]))
  const next = { ...base, ...p.patch } as OgState
  const chips = Object.fromEntries(CHIP_KEYS.map((c) => [c.id, chipOff()])) as Record<ChipKey, Chip>
  chips.title = chipOff({ radius: 28, padX: 28, padY: 18 })
  chips.subtitle = chipOff({ radius: 24, padX: 24, padY: 16 })
  if (p.chips) {
    ;(Object.keys(p.chips) as ChipKey[]).forEach((k) => {
      chips[k] = { ...chips[k], ...p.chips![k] }
    })
  }
  next.chips = chips
  return next
}

export function presetPreview(p: Preset): OgState {
  return presetState(p, DEFAULT_OG_STATE)
}

export const easeOut = (t: number) => 1 - Math.pow(1 - t, 3)
export const easeSmooth = (t: number) => (t <= 0 ? 0 : t >= 1 ? 1 : 1 - Math.pow(2, -10 * t))
export const clamp01 = (v: number) => Math.max(0, Math.min(1, v))
export const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms))
