export function randomEmoji(pool: readonly string[] = EMOJI_POOL) {
  return pool[Math.floor(Math.random() * pool.length)] ?? DEFAULT_EMOJI
}

export function emojiFromSeed(seed: string, pool: readonly string[] = EMOJI_POOL) {
  if (!pool.length) return DEFAULT_EMOJI
  let hash = 0
  for (let index = 0; index < seed.length; index++) hash = (hash + seed.charCodeAt(index) * (index + 1)) % pool.length
  return pool[hash] ?? DEFAULT_EMOJI
}
